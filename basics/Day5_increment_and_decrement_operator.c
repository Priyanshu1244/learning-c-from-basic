#include<stdio.h>

int main(){

    int a = 5;  //a is initialized as 5

    printf("%d\n",a);    //value of a is 5

    printf("%d\n",++a);  //value will update then print

    printf("%d\n",--a);  //value will update then print

    printf("%d\n",a++);  //value will print then update

    printf("%d\n",a--);  //value will print then update

    return 0;

}